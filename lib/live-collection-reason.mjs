// Bounded, price-free reasons that can be attributed to one requested symbol.
// Unrecognised codes (including credentials, ownership, SQL and integrity failures)
// cannot justify treating the rest of a collection as publishable.
const symbolReasons = new Set([
  "LIVE_CLOUD_OBSERVATION_MISSING", "LIVE_CLOUD_OBSERVATION_INVALID", "LIVE_CLOUD_RATE_EVIDENCE_INVALID",
  "LIVE_CLOUD_ATTEMPT_ALREADY_RESERVED", "LIVE_CLOUD_CHILD_RESULT_MISSING", "LIVE_CLOUD_CHILD_ERRORED",
  "LIVE_CLOUD_CHILD_TERMINATED", "LIVE_CLOUD_CHILD_NOT_COMPLETE", "LIVE_CLOUD_QUOTE_DATE",
  "LIVE_CLOUD_OBSERVATION_WINDOW", "DIAG_UNKNOWN_TRANSPORT_FAILURE", "DIAG_RATE_SLOT_MISSED",
  "DIAG_COLLECTION_DEADLINE", "DIAG_RETRY_EXHAUSTED", "DIAG_TRANSPORT_CONNECTION_RESET", "DIAG_TRANSPORT_DNS",
  "DIAG_TRANSPORT_TIMEOUT", "DIAG_TRANSPORT_SOCKET", "DIAG_TRANSPORT_CONNECTION_REFUSED", "KIS_BUSINESS_NETWORK_ERROR",
  "KIS_INVALID_QUOTE", "KIS_INVALID_OHLC", "KIS_RESPONSE_INVALID", "KIS_RATE_LIMITED", "KIS_SYMBOL_MISMATCH",
  "KIS_MINUTE_OBSERVATION_INVALID", "KIS_MINUTE_OBSERVATION_TIMESTAMP_INVALID", "KIS_MINUTE_OBSERVATION_TIMESTAMP_MISSING",
]);

export function isLiveMissingReason(reason) {
  return symbolReasons.has(reason) || typeof reason === "string" && /^KIS_HTTP_(400|404|408|422|429|5[0-9]{2})$/u.test(reason);
}
