import assert from "node:assert/strict";
import { calculateTechnicalStrength } from "../lib/technical-strength.mjs";
import { calculateTechnicalModelFeatures } from "../lib/technical-model-features.mjs";
import { calculateTrendStrength } from "../lib/trend-strength.mjs";
import { calculateEntryStrength } from "../lib/entry-strength.mjs";
import { calculateCombinedTechnicalScore } from "../lib/combined-technical-score.mjs";
import { mergeProvisionalCandle } from "../lib/intraday-model-b-official-signal.mjs";
import { assertImmutableIntradayModelTopSignal, buildIntradayModelTopSignal, validateIntradayModelTopSignal } from "../lib/intraday-model-top-official-signal.mjs";

const dateAt = (offset) => { const date = new Date("2026-10-02T00:00:00Z"); date.setUTCDate(date.getUTCDate() - offset); return date.toISOString().slice(0, 10).replaceAll("-", ""); };
const rows = Array.from({ length: 260 }, (_, index) => [dateAt(index), 100 + index / 10, 102 + index / 10, 98 + index / 10, 100 + index / 10, 1000 + index]);
const formulaHashes = { "A-v1": "a", "A-v2": "a2", "B-v1": "b", "C-v1": "c", "D-v1": "d" };
const seed = { requestedDate: "2026-10-02", contentHash: "seed", sourceManifest: { modelFormulaHashes: formulaHashes, sources: { officialDailyPrice: { normalizedInputHash: "daily" } } }, records: [{ code: "000001", name: "A", market: "KOSPI", eligible: true, rows }, { code: "000002", name: "B", market: "KOSDAQ", eligible: true, rows }, { code: "000003", name: "C", market: "KOSPI", eligible: false, ineligibleReasons: ["insufficientHistory"], rows: [] }] };
const quote = (code, price, options = {}) => ({ code, source: "KIS", priceBasis: "lastQuotedPrice", asOfDate: "2026-10-06", asOfTime: "14:30:10", receivedAt: "2026-10-06T05:30:11.000Z", open: price - 1, high: price + 2, low: price - 2, price, volume: 2000, change: 5, rate: 2.5, ...options });
const input = { seed, signalDate: "2026-10-06", collectionStartedAt: "2026-10-06T05:30:00.000Z", collectionCompletedAt: "2026-10-06T05:31:00.000Z", observationType: "TEST_FIXTURE" };
const signal = buildIntradayModelTopSignal({ ...input, quotesByCode: new Map([["000001", quote("000001", 200)], ["000002", quote("000002", 190)]]) });
assert.equal(signal.status, "READY");
assert.equal(signal.observationType, "TEST_FIXTURE");
assert.deepEqual(validateIntradayModelTopSignal(signal), []);
assert.equal(signal.collection.successful, 2);
assert.equal(signal.collection.ineligible, 1);
for (const modelVersion of ["A-v1", "B-v1", "C-v1", "D-v1"]) {
  assert.equal(signal.top5[modelVersion].length, 2);
  assert.deepEqual(signal.records.filter((record) => record.dataStatus === "AVAILABLE").map((record) => record.ranks[modelVersion]).sort(), [1, 2]);
  assert.ok(signal.records[0].observationIds[modelVersion]);
}
const first = signal.records.find((record) => record.ticker === "000001");
const firstQuote = quote("000001", 200);
const merged = mergeProvisionalCandle(rows, firstQuote);
const expectedA = calculateTechnicalStrength(merged, null);
const features = calculateTechnicalModelFeatures(merged, firstQuote);
const expectedB = calculateTrendStrength(features);
const expectedC = calculateEntryStrength(features);
const expectedD = calculateCombinedTechnicalScore(expectedB.trendStrength, expectedC.entryStrength);
assert.equal(first.scores["A-v1"], expectedA.finalTechnicalScore);
assert.equal(first.scores["B-v1"], expectedB.trendStrength);
assert.equal(first.scores["C-v1"], expectedC.entryStrength);
assert.equal(first.scores["D-v1"], expectedD);
assert.equal(first.provisionalOhlcv.rate, 2.5);
assert.equal(signal.outcomeTracking.status, "PENDING");
assert.equal(assertImmutableIntradayModelTopSignal(null, signal), "create");
assert.equal(assertImmutableIntradayModelTopSignal(signal, signal), "idempotent");
assert.throws(() => assertImmutableIntradayModelTopSignal(signal, { ...signal, contentHash: "changed" }), /IMMUTABLE/);
assert.throws(() => buildIntradayModelTopSignal({ ...input, seed: { ...seed, requestedDate: "2026-10-06" }, quotesByCode: new Map() }), /STRICTLY_PRIOR/);
const partial = buildIntradayModelTopSignal({ ...input, quotesByCode: new Map([["000001", quote("000001", 200)]]) });
assert.equal(partial.status, "FAILED_COLLECTION");
assert.equal(partial.records.find((record) => record.ticker === "000002").reason, "quoteMissing");
const early = buildIntradayModelTopSignal({ ...input, quotesByCode: new Map([["000001", quote("000001", 200, { asOfTime: "14:29:59", receivedAt: "2026-10-06T05:30:00.000Z" })], ["000002", quote("000002", 190)]]) });
assert.equal(early.records.find((record) => record.ticker === "000001").reason, "quoteOutsideSignalWindow");
const future = buildIntradayModelTopSignal({ ...input, quotesByCode: new Map([["000001", quote("000001", 200, { receivedAt: "2026-10-06T05:30:09.000Z" })], ["000002", quote("000002", 190)]]) });
assert.equal(future.records.find((record) => record.ticker === "000001").reason, "quoteFromFuture");
const rerun = buildIntradayModelTopSignal({ ...input, quotesByCode: new Map([["000001", quote("000001", 200)], ["000002", quote("000002", 190)]]) });
assert.equal(rerun.contentHash, signal.contentHash);
console.log("intraday A/B/C/D 14:30 score·rank·provenance·immutability·no-look-ahead tests passed");
