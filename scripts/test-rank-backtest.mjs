import assert from "node:assert/strict";
import fs from "node:fs";
import fsp from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { buildRankBacktest, hashObject } from "../lib/rank-backtest-engine.mjs";
import { saveRankBacktest } from "../lib/rank-backtest-storage.mjs";

const config=JSON.parse(fs.readFileSync(new URL("../config/rank-backtest.json",import.meta.url),"utf8"));
const makeSnapshot=(date,shift=0)=>({schemaVersion:5,asOfDate:date,modelDefinitions:{A:{modelVersion:"A-v1"},B:{modelVersion:"B-v1"},C:{modelVersion:"C-v1"},D:{modelVersion:"D-v1"}},records:Array.from({length:60},(_,index)=>{const rank=index+1,value=rank===60?null:rank+shift;return {code:String(rank).padStart(6,"0"),scores:{modelA:61-rank,modelB:61-rank,modelC:61-rank,modelD:61-rank},ranks:{modelA:rank,modelB:rank,modelC:rank,modelD:rank},scoresByVersion:{"A-v1":61-rank},ranksByVersion:{"A-v1":rank},rankingUniverseCount:{modelA:60,modelB:60,modelC:60,modelD:60},rankPercentile:{modelA:rank/60,modelB:rank/60,modelC:rank/60,modelD:rank/60},futureReturns:{future1dReturn:value,future5dReturn:value+1,future20dReturn:value+2},backtestReturns:{returns:{nextOpenToT1CloseReturn:value===null?null:value+100,nextOpenToT5CloseReturn:value===null?null:value+101,nextOpenToT20CloseReturn:value===null?null:value+102}}};})});
const snapshots=["2026-01-02","2026-01-05"].map((date,index)=>{const snapshot=makeSnapshot(date,index);return {date,hash:hashObject(snapshot),snapshot};});
const options={snapshots,models:["A-v1","B-v1"],evaluations:["predictive","executable"],config,includeProvisional:true,generatedAt:"2026-08-17T00:00:00.000Z"};
const result=buildRankBacktest(options);
const metric=(evaluation,bucket)=>result.metrics.find((item)=>item.modelVersion==="A-v1"&&item.evaluation===evaluation&&item.horizon==="T1"&&item.rankBucket===bucket);
assert.equal(metric("predictive","TOP10").observationCount,20);
assert.equal(metric("predictive","TOP20").observationCount,40);
assert.equal(metric("predictive","TOP50").observationCount,100);
assert.equal(metric("predictive","TOP10_PERCENT").observationCount,12);
assert.equal(metric("predictive","ALL_ELIGIBLE").pendingCount,2);
assert.equal(metric("predictive","ALL_ELIGIBLE").observationCount,118);
assert.ok(metric("executable","TOP10").meanReturn>metric("predictive","TOP10").meanReturn+90);
assert.equal(metric("predictive","TOP10").meanReturn,6);
assert.equal(metric("predictive","TOP10").medianReturn,6);
assert.equal(metric("predictive","TOP10").positiveRate,1);
assert.equal(metric("predictive","TOP10").signalDateCount,2);
assert.equal(metric("predictive","TOP10").status,"INSUFFICIENT_DATA");
const common=result.commonComparisonMetrics.find((item)=>item.modelVersion==="A-v1"&&item.evaluation==="predictive"&&item.horizon==="T1"&&item.rankBucket==="TOP10");
assert.equal(common.comparisonUniverseByDate.length,2);
assert.equal(common.comparisonUniverseByDate[0].count,59);
assert.ok(common.averageCrossSectionalSpread<0);
const noFallback=buildRankBacktest({...options,models:["A-v2"],evaluations:["predictive"]});
assert.ok(noFallback.metrics.every((item)=>item.status==="VERSION_DATA_NOT_AVAILABLE"));
const pendingSnapshot=makeSnapshot("2026-02-02");for(const record of pendingSnapshot.records)record.futureReturns.future1dReturn=null;
const pending=buildRankBacktest({...options,snapshots:[{date:"2026-02-02",hash:hashObject(pendingSnapshot),snapshot:pendingSnapshot}],models:["A-v1"],evaluations:["predictive"]});
assert.equal(pending.metrics.find((item)=>item.horizon==="T1").status,"NO_RESOLVED_RETURNS");
assert.equal(pending.metrics.find((item)=>item.horizon==="T1").meanReturn,null);
assert.equal(buildRankBacktest(options).contentHash,result.contentHash);
assert.doesNotMatch(fs.readFileSync(new URL("../lib/rank-backtest-engine.mjs",import.meta.url),"utf8"),/(?:import|from).*intraday/i);

const root=await fsp.mkdtemp(path.join(os.tmpdir(),"rank-backtest-"));
const first={...result,generatedAt:"2026-08-17T00:00:00.000Z"};await saveRankBacktest(first,{root});
const latest=path.join(root,"data","backtests","rank-evaluation","latest.json"),before=await fsp.readFile(latest,"utf8");
const failed={...result,generatedAt:"2026-08-17T00:01:00.000Z"};await assert.rejects(()=>saveRankBacktest(failed,{root,hooks:{beforeRename:()=>{throw new Error("synthetic failure");}}}));
assert.equal(await fsp.readFile(latest,"utf8"),before);
assert.equal((await fsp.readdir(path.dirname(latest))).some((name)=>name.endsWith(".lock")||name.endsWith(".tmp")||name.endsWith(".bak")),false);
await fsp.rm(root,{recursive:true,force:true});
console.log("순위 백테스트 분리·bucket·benchmark·common Universe·hash·원자저장 테스트 통과");
